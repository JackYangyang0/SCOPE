def select_tasks(protocol: dict[str, Any], *, task_ids: Sequence[str] | None = None,
                 limit: int | None = None, blocks: Sequence[str] | None = None,
                 only_pending: bool = True,
                 include_aliases: bool = True) -> list[str]:
    records = (protocol.get("tasks") or {}).get("task_records") or []
    order = (protocol.get("tasks") or {}).get("order") or [record["task_id"] for record in records]
    by_id = {record["task_id"]: record for record in records}
    wanted = set(task_ids) if task_ids else None
    result: list[str] = []
    for task_id in order:
        record = by_id.get(task_id)
        if record is None:
            continue
        if wanted is not None and task_id not in wanted:
            continue
        if blocks and str(record.get("block", "")).upper() not in {b.upper() for b in blocks}:
            continue
        if not include_aliases and record.get("kind") == "alias":
            continue
        result.append(task_id)
        if limit and len(result) >= limit:
            break
    return result


def run_campaign(paths: CampaignPaths, protocol: dict[str, Any],
                 options: RunOptions, *, task_ids: Sequence[str] | None = None,
                 limit: int | None = None, blocks: Sequence[str] | None = None,
                 stop_on_infra_error: bool = True,
                 progress: Any = None) -> dict[str, Any]:
    queue = select_tasks(protocol, task_ids=task_ids, limit=limit, blocks=blocks)
    results: list[dict[str, Any]] = []
    infra_failures = 0
    for task_id in queue:
        status = read_status(paths, task_id)
        if status.get("status") == "resolved":
            results.append({"task_id": task_id, "skipped": "already resolved"})
            continue
        try:
            status = run_task(paths, protocol, task_id, options, progress=progress)
            results.append({"task_id": task_id, "status": status.get("status"),
                            "argv": status.get("argv"),
                            "config_hash": status.get("config_hash")})
            if status.get("status") == "infra_incomplete":
                infra_failures += 1
        except InfraError as exc:
            infra_failures += 1
            results.append({"task_id": task_id, "status": "infra_incomplete",
                            "error": str(exc)})
            if stop_on_infra_error:
                break
    summary = {
        "runner_version": RUNNER_VERSION,
        "campaign_id": options.campaign_id,
        "queue": queue,
        "completed": results,
        "infra_failures": infra_failures,
        "finished_at": utc_now(),
        "counts": _count_statuses(paths, queue),
    }
    write_json(paths.analysis / "run_summary.json", summary)
    return summary


def abandon_task(paths: CampaignPaths, task_id: str, *, reason: str) -> dict[str, Any]:
    directory = paths.task_dir(task_id)
    if not directory.exists():
        raise ProtocolError(f"{task_id}: nothing to abandon (no task directory)")
    status = read_status(paths, task_id)
    archive_root = ensure_dir(paths.tasks / "_abandoned")
    stamp = utc_now().replace(":", "").replace("-", "")
    target = archive_root / f"{task_id}.{stamp}"
    directory.replace(target)
    record = {
        "task_id": task_id,
        "abandoned_at": utc_now(),
        "reason": reason,
        "previous_status": status.get("status"),
        "previous_attempts": len(status.get("attempts") or []),
        "archived_to": str(target),
        "independent_n_unchanged": True,
        "note": "the slot will be re-run under the same logical_run_id",
    }
    append_jsonl(paths.audit / "abandoned.jsonl", record)
    return record

EVIDENCE_GLOBS = (
    "results/check/*.json",
    "results/code/final_code.json",
    "results/defect/*.json",
    "results/tuning/*.json",
    "data/IRs/ir_patch/optir.verified.json",
    "gemm_code/*/*/terminal_chain.json",
)
EVIDENCE_MAX_FILES = 400
EVIDENCE_MAX_BYTES = 48 * 1024 * 1024


def _harvest_app_evidence(workspace, destination: Path, *, limit_files: int = EVIDENCE_MAX_FILES,
                          limit_bytes: int = EVIDENCE_MAX_BYTES) -> dict[str, Any]:
    files: list[dict[str, Any]] = []
    total = 0
    source_root = workspace.root / "SCOPE"
    for pattern in EVIDENCE_GLOBS:
        for source in sorted(source_root.glob(pattern)):
            if not source.is_file():
                continue
            if len(files) >= limit_files or total >= limit_bytes:
                break
            try:
                data = source.read_bytes()
            except OSError:
                continue
            if total + len(data) > limit_bytes:
                continue
            relative = source.relative_to(source_root)
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            files.append({"path": str(relative), "sha256": sha256_bytes(data),
                          "size": len(data)})
            total += len(data)
    return {"files": files, "file_count": len(files), "bytes": total,
            "truncated": len(files) >= limit_files or total >= limit_bytes}


def _diagnose_generation(paths: CampaignPaths, task_id: str,
                         evidence: dict[str, Any]) -> dict[str, Any]:
    directory = paths.task_dir(task_id) / "app_evidence"
    chains: list[dict[str, Any]] = []
    for path in sorted(directory.glob("gemm_code/*/*/terminal_chain.json")):
        try:
            manifest = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        summary = ((manifest.get("verification") or {}) if isinstance(
            manifest.get("verification"), dict) else {})
        chains.append({
            "chain_id": path.parent.name,
            "accepted": manifest.get("accepted"),
            "compile_status": summary.get("compile_status"),
            "correctness_status": summary.get("correctness_status"),
            "runtime_safety_status": summary.get("runtime_safety_status"),
            "gflops_mean": summary.get("gflops_mean"),
        })
    evolution: dict[str, Any] = {}
    for candidate in ("results/check/evolution_summary.json",
                      "results/check/top_3_terminal_results.json"):
        path = directory / candidate
        if not path.exists():
            continue
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(payload, dict):
            evolution[candidate] = {
                key: payload.get(key) for key in
                ("terminal_chain_count", "verified_terminal_chain_count",
                 "frontier_state_count", "failed_strategy_counts",
                 "best_overall_strategy_id", "applied_strategy_ids")
                if key in payload
            }
            if candidate.endswith("top_3_terminal_results.json"):
                evolution["accepted_candidates"] = len(payload.get("results") or [])
    accepted = sum(1 for chain in chains if chain["accepted"])
    correctness = [chain for chain in chains if chain["correctness_status"] == "pass"]
    compile_pass = [chain for chain in chains if chain["compile_status"] == "pass"]
    if chains and not accepted:
        if not compile_pass:
            reason = "no chain compiled"
        elif not correctness:
            reason = "every terminal chain failed the method's own correctness check"
        else:
            reason = "terminal chains compiled but runtime safety did not pass"
    elif not chains:
        reason = "the method produced no terminal chain"
    else:
        reason = "at least one chain was accepted"
    return {"chains": chains, "chain_count": len(chains), "accepted_count": accepted,
            "compile_pass_count": len(compile_pass),
            "correctness_pass_count": len(correctness),
            "reason": reason, "evolution": evolution,
            "evidence": evidence}

def _count_statuses(paths: CampaignPaths, task_ids: Iterable[str]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for task_id in task_ids:
        status = read_status(paths, task_id).get("status", "planned")
        counts[status] = counts.get(status, 0) + 1
    return dict(sorted(counts.items()))


