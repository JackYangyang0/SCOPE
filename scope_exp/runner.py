def _generation_failure_category(paths: CampaignPaths, task_id: str,
                                 attempt_id: str,
                                 generation: dict[str, Any]) -> str | None:
    if generation.get("timed_out"):
        return None
    try:
        rows = read_jsonl(paths.attempt_ledger(task_id, attempt_id))
    except (OSError, ValueError):
        rows = []
    failed = [row for row in rows if row.get("failed")]
    succeeded = [row for row in rows if not row.get("failed")]
    if rows and failed and not succeeded:
        return f"all {len(failed)} API request(s) failed; no request succeeded"
    text = (generation.get("stdout_tail") or "") + "\n" + (generation.get("stderr_tail") or "")
    for token in API_FAILURE_MARKERS:
        if token in text:
            return f"generation output contains an API/infrastructure error: {token!r}"
    if not rows and generation.get("exit_code") not in (0, None):
        return (f"the application exited {generation.get('exit_code')} before any "
                "instrumented API request was recorded")
    return None


def _write_logs(paths: CampaignPaths, task_id: str, attempt_id: str,
                generation: dict[str, Any], stdout_log: Path, stderr_log: Path,
                workspace: isolation.Workspace) -> None:
    stdout_source = generation.get("stdout_path")
    stderr_source = generation.get("stderr_path")
    for source, target in ((stdout_source, stdout_log), (stderr_source, stderr_log)):
        if source and Path(source).exists():
            target.write_bytes(Path(source).read_bytes())
        else:
            target.write_text("", encoding="utf-8")
    if generation.get("timed_out"):
        append_jsonl(paths.attempt_events(task_id, attempt_id),
                     {"event": "generation_timeout", "at": utc_now(),
                      "budget_seconds": generation.get("wall_seconds")})


def _record_artifacts(paths: CampaignPaths, task_id: str, status: dict[str, Any],
                      attempt_id: str, artifacts: dict[str, Any]) -> dict[str, Any]:
    present = artifacts.get("present") or {}
    hashes = {}
    for name, path in (artifacts.get("paths") or {}).items():
        candidate = Path(path)
        if candidate.is_file():
            hashes[name] = sha256_file(candidate)
    status["application_artifacts"] = {"present": present, "hashes": hashes}
    append_jsonl(paths.attempt_events(task_id, attempt_id),
                 {"event": "artifacts_collected", "at": utc_now(),
                  "present": present})
    if not any(present.values()):
        status["generation_note"] = "the application produced none of the expected artifacts"
    return status


