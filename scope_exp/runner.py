RUNNER_VERSION = "scope-exp-runner-v1"
STATUS_SCHEMA = "scope-exp-task-status-v1"

TERMINAL_STATUSES = {"resolved", "no_candidate", "generation_failed",
                     "infra_incomplete"}
RESUMABLE_STATUSES = {"planned", "started", "generation_done", "frozen_top1",
                      "validated", "timed", "infra_incomplete"}


def read_status(paths: CampaignPaths, task_id: str) -> dict[str, Any]:
    path = paths.task_status(task_id)
    if not path.exists():
        return {"status_schema": STATUS_SCHEMA, "task_id": task_id,
                "status": "planned", "attempts": [], "outcome": None}
    return read_json(path)


def write_status(paths: CampaignPaths, task_id: str, status: dict[str, Any],
                 *, event: str | None = None, attempt_id: str | None = None,
                 **event_fields: Any) -> dict[str, Any]:
    status = dict(status)
    status["status_schema"] = STATUS_SCHEMA
    status["task_id"] = task_id
    status["updated_at"] = utc_now()
    status["harness_version"] = HARNESS_VERSION
    write_json(paths.task_status(task_id), status)
    if event:
        attempt = attempt_id or (status.get("attempts") or [{}])[-1].get("attempt_id")
        if attempt:
            append_jsonl(paths.attempt_events(task_id, attempt),
                         {"event": event, "at": utc_now(), **event_fields})
    return status


def _attempt_record(attempt_id: str, kind: str) -> dict[str, Any]:
    return {"attempt_id": attempt_id, "kind": kind, "started_at": utc_now(),
            "finished_at": None, "exit_code": None, "timed_out": False,
            "wall_seconds": None, "resumed": False}


def workspace_config(config: dict[str, Any], *, task_id: str) -> dict[str, Any]:
    from .redact import is_secret_field

    payload = json.loads(json.dumps(config))
    for section in (payload.get("llm") or {}).values():
        if not isinstance(section, dict):
            continue
        for key, value in list(section.items()):
            if is_secret_field(key, value):
                section[key] = ""
    llm = payload.setdefault("llm", {})
    llm["provider"] = llm.get("provider")
    payload.setdefault("execution", {})
    payload["_scope_exp"] = {
        "task_id": task_id,
        "harness_version": HARNESS_VERSION,
        "note": "generated by the experiment harness; credentials are never written",
    }
    return payload


def write_workspace_config(workspace: isolation.Workspace, config: dict[str, Any],
                           *, task_id: str) -> Path:
    path = workspace.package_dir / "conf.yaml"
    payload = workspace_config(config, task_id=task_id)
    path.write_text(yaml.safe_dump(payload, sort_keys=False, allow_unicode=True),
                    encoding="utf-8")
    return path


