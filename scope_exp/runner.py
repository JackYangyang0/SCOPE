def _collect_attempt_ledger(paths: CampaignPaths, task_id: str, attempt_id: str,
                            workspace: isolation.Workspace | None,
                            effective: dict[str, Any], options: RunOptions,
                            protocol: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if workspace is not None:
        instrumented = Path(workspace.root) / f"api_ledger.{attempt_id}.jsonl"
        if instrumented.exists():
            for raw in read_jsonl(instrumented):
                tokens = raw.get("tokens") or {}
                rows.append(ledger.record_request(
                    request_id=raw.get("request_id"),
                    task_id=task_id, attempt_id=attempt_id,
                    phase=raw.get("phase"), call_type=raw.get("call_type"),
                    started_at=str(raw.get("started_at")),
                    duration_seconds=raw.get("duration_seconds"),
                    failed=bool(raw.get("failed")), tokens=tokens,
                    returned_model=raw.get("model"),
                    usage_source="instrumented_client",
                    error=raw.get("error")))
    if not rows and workspace is not None:
        rq3 = (isolation.artifact_paths(workspace)["check"] /
               "rq3_optimization_record.json")
        aggregates = ledger.app_phase_aggregates(rq3)
        total = aggregates.get("total") or {}
